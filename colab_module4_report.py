def format_report(
    answers: Dict[str, str],
    tender_no: str,
    sources_used: Dict[str, List[Dict[str, Any]]],
) -> str:
    n_docs = len(set(rag_index.sources))
    n_chunks = len(rag_index.chunks)
    date_str = ANALYSIS_DATE.strftime("%Y-%m-%d %H:%M")

    lines: List[str] = []
    lines.append("=" * 60)
    lines.append("📊 АНАЛИЗ ТЕНДЕРНОЙ ДОКУМЕНТАЦИИ")
    lines.append("=" * 60)
    lines.append(f"Номер тендера / ИКЗ: {tender_no or answers.get('Номер тендера / ИКЗ', 'Не указано')}")
    lines.append(f"Дата анализа: {date_str}")
    lines.append(f"Всего документов: {n_docs}")
    lines.append(f"Всего чанков: {n_chunks}")
    lines.append("")

    # секции 1–5
    current_section = None
    for section, field, _q, _v in REPORT_FIELDS:
        if section != current_section:
            if current_section is not None:
                lines.append("")
            lines.append("=" * 60)
            lines.append(section)
            lines.append("=" * 60)
            current_section = section
        lines.append(f"{field}: {answers.get(field, 'Не указано')}")

    # секция 6
    lines.append("")
    lines.append("=" * 60)
    lines.append("6. РИСКИ И РЕКОМЕНДАЦИИ")
    lines.append("=" * 60)
    for _section, field in SECTION6_FIELDS:
        lines.append(f"{field}: {answers.get(field, 'Не указано')}")

    # источники
    lines.append("")
    lines.append("=" * 60)
    lines.append("7. ИСПОЛЬЗОВАННЫЕ ИСТОЧНИКИ ПО ПУНКТАМ")
    lines.append("=" * 60)
    for field, items in sources_used.items():
        if not items:
            lines.append(f"{field}: источники не найдены")
            continue
        lines.append(f"{field}:")
        for it in items[:8]:
            chunk = f", чанк #{it['chunk']}" if it.get("chunk") else ""
            lines.append(f"  • {it['source']}{chunk} (score={it.get('score', 0)})")

    # сводный список уникальных файлов
    all_sources = sorted({it["source"] for items in sources_used.values() for it in items})
    lines.append("")
    lines.append("Уникальные файлы-источники:")
    if all_sources:
        for s in all_sources:
            lines.append(f"  • {s}")
    else:
        lines.append("  • (нет)")

    lines.append("=" * 60)
    return "\n".join(lines) + "\n"


