def _clean_answer(text: str) -> str:
    text = (text or "").strip()
    if not text:
        return "Не указано"
    low = text.lower()
    empty_markers = [
        "не указано",
        "не найден",
        "нет информации",
        "не удалось",
        "в контексте нет",
        "в предоставленном контексте нет",
        "информация отсутствует",
        "не могу ответить",
    ]
    if any(m in low for m in empty_markers) and len(text) < 180:
        return "Не указано"
    return text


def _extract_tender_number(raw: str) -> str:
    """
    Извлекает номер тендера / ИКЗ из ответа модели.
    Предпочитает типичные длинные коды (ИКЗ ~20 цифр, номера извещений и т.п.).
    """
    if not raw or raw == "Не указано":
        return ""

    # ИКЗ: обычно 36 цифр или длинная цифровая строка; также буквенно-цифровые номера
    patterns = [
        r"\b\d{20,36}\b",                          # ИКЗ / длинный цифровой
        r"\b[A-Za-z]\d{10,}\b",                    # вида B3107261017496
        r"\b\d{2}-\d{10,}\b",
        r"\b№?\s*([A-Za-z0-9][A-Za-z0-9\-]{7,})\b",
    ]
    for pat in patterns:
        m = re.search(pat, raw)
        if m:
            num = m.group(1) if m.lastindex else m.group(0)
            num = re.sub(r"^[№#\s]+", "", num).strip()
            num = re.sub(r"[^\w\-]", "", num)
            if len(num) >= 6:
                return num

    # fallback: первая «плотная» токен-последовательность
    tokens = re.findall(r"[A-Za-z0-9][A-Za-z0-9\-]{5,}", raw)
    for t in tokens:
        if any(ch.isdigit() for ch in t):
            return t
    return ""


def _ask_rag(question: str, top_k: int = TOP_K_REPORT) -> str:
    hits = rag_index.search(question, top_k=top_k)
    if not hits:
        return "Не указано"
    context = "\n\n---\n\n".join(
        f"[Источник: {h['source']} | score={h['score']:.3f}]\n{h['text']}" for h in hits
    )
    answer = ask_deepseek(question, context=context)
    return _clean_answer(answer)


def _safe_filename_part(value: str) -> str:
    value = re.sub(r"[^\w\-]+", "_", value, flags=re.UNICODE)
    value = re.sub(r"_+", "_", value).strip("_")
    return value[:80] if value else ""


def _build_report_filename(tender_no: str) -> str:
    now = datetime.now()
    date_s = now.strftime("%Y%m%d")
    time_s = now.strftime("%H%M%S")
    if tender_no:
        safe = _safe_filename_part(tender_no)
        return f"Анализ_тендера_{safe}_{date_s}.txt"
    return f"Анализ_тендера_{date_s}_{time_s}.txt"


def _format_report(answers: dict, tender_no: str, analysis_date: str) -> str:
    n_docs = len(set(rag_index.sources)) if getattr(rag_index, "sources", None) else 0
    n_chunks = len(rag_index.chunks) if getattr(rag_index, "chunks", None) else 0

    lines = []
    lines.append("=" * 60)
    lines.append("📊 АНАЛИЗ ТЕНДЕРНОЙ ДОКУМЕНТАЦИИ")
    lines.append("=" * 60)
    lines.append(f"Номер тендера / ИКЗ: {tender_no or answers.get('Номер тендера / ИКЗ', 'Не указано')}")
    lines.append(f"Дата анализа: {analysis_date}")
    lines.append(f"Всего документов: {n_docs}")
    lines.append(f"Всего чанков: {n_chunks}")
    lines.append("")

    current_section = None
    for section, field, _question in REPORT_FIELDS:
        if section != current_section:
            if current_section is not None:
                lines.append("")
            lines.append("=" * 60)
            lines.append(section)
            lines.append("=" * 60)
            current_section = section
        value = answers.get(field, "Не указано")
        lines.append(f"{field}: {value}")

    lines.append("=" * 60)
    return "\n".join(lines) + "\n"


