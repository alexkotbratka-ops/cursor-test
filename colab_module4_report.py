def _is_empty_answer(text: str) -> bool:
    text = (text or "").strip()
    if not text:
        return True
    low = text.lower()
    markers = [
        "не указано",
        "не найден",
        "нет информации",
        "не удалось",
        "в контексте нет",
        "в предоставленном контексте нет",
        "в предоставленном контексте не",
        "информация отсутствует",
        "ответить на вопрос невозможно",
        "невозможно определить",
        "не могу найти",
        "не могу ответить",
        "отсутствует",
    ]
    if len(text) < 220 and any(m in low for m in markers):
        # если есть явное содержательное исключение — не считаем пустым
        if re.search(r"\d{3,}", text) and ("руб" in low or "инн" in low or "%" in text):
            return False
        return True
    return False


def _clean_answer(text: str) -> str:
    text = (text or "").strip()
    if _is_empty_answer(text):
        return "Не указано"
    return text


def _source_priority(source: str) -> float:
    s = (source or "").lower().replace("\\", "/")
    bonus = 0.0
    for i, kw in enumerate(PRIORITY_KEYWORDS):
        if kw in s:
            # чем раньше в списке — тем выше бонус
            bonus = max(bonus, 0.35 - i * 0.02)
    return bonus


def _search_hits(query: str, top_k: int = TOP_K) -> List[Dict[str, Any]]:
    raw = rag_index.search(query, top_k=max(top_k * 3, top_k))
    if not raw:
        return []
    # переранжирование с приоритетом источников
    rescored = []
    for h in raw:
        score = float(h.get("score", 0.0)) + _source_priority(h.get("source", ""))
        item = dict(h)
        item["score"] = score
        rescored.append(item)
    rescored.sort(key=lambda x: x["score"], reverse=True)
    return rescored[:top_k]


def _merge_hits(hit_lists: List[List[Dict[str, Any]]], top_k: int = TOP_K) -> List[Dict[str, Any]]:
    best: Dict[Tuple[str, str], Dict[str, Any]] = {}
    for hits in hit_lists:
        for h in hits:
            key = (h.get("source", ""), h.get("text", ""))
            if key not in best or h["score"] > best[key]["score"]:
                best[key] = h
    merged = sorted(best.values(), key=lambda x: x["score"], reverse=True)
    return merged[:top_k]


def _format_context(hits: List[Dict[str, Any]]) -> str:
    parts = []
    for i, h in enumerate(hits, start=1):
        parts.append(
            f"[Фрагмент {i} | Источник: {h.get('source', '?')} | score={h.get('score', 0):.3f}]\n"
            f"{h.get('text', '')}"
        )
    return "\n\n---\n\n".join(parts)


def _chunk_index_for(source: str, text: str) -> Optional[int]:
    """Номер чанка в rag_index (1-based), если удаётся сопоставить."""
    try:
        for i, (s, t) in enumerate(zip(rag_index.sources, rag_index.chunks)):
            if s == source and t == text:
                return i + 1
    except Exception:
        pass
    return None


def _record_sources(field: str, hits: List[Dict[str, Any]], store: Dict[str, List[Dict[str, Any]]]):
    seen = set()
    items = []
    for h in hits:
        src = h.get("source", "?")
        txt = h.get("text", "")
        key = (src, txt[:80])
        if key in seen:
            continue
        seen.add(key)
        items.append(
            {
                "source": src,
                "chunk": _chunk_index_for(src, txt),
                "score": round(float(h.get("score", 0.0)), 4),
            }
        )
    store[field] = items


def ask_with_variants(
    question: str,
    variants: Optional[List[str]] = None,
    top_k: int = TOP_K,
    retry_if_empty: bool = True,
) -> Tuple[str, List[Dict[str, Any]]]:
    """
    Основной вопрос + альтернативные формулировки.
    Объединяет чанки, спрашивает DeepSeek, при «Не указано» — повтор с переформулировкой.
    Возвращает (ответ, hits).
    """
    variants = variants or []
    queries = [question] + list(variants)

    hit_lists = [_search_hits(q, top_k=top_k) for q in queries]
    hits = _merge_hits(hit_lists, top_k=top_k)

    if not hits:
        return "Не указано", []

    context = _format_context(hits)
    prompt = f"{PRIORITY_PROMPT}\n\nВопрос: {question}"
    answer = _clean_answer(ask_deepseek(prompt, context=context))

    if retry_if_empty and answer == "Не указано" and variants:
        # повтор: усиленный запрос + другие формулировки
        retry_q = (
            variants[-1]
            + " Ответь только фактами из контекста. Если есть хотя бы частичный ответ — приведи его."
        )
        retry_hits = _merge_hits(
            [_search_hits(retry_q, top_k=top_k), hits],
            top_k=top_k,
        )
        retry_ctx = _format_context(retry_hits)
        retry_ans = _clean_answer(ask_deepseek(f"{PRIORITY_PROMPT}\n\nВопрос: {retry_q}", context=retry_ctx))
        if retry_ans != "Не указано":
            return retry_ans, retry_hits

    return answer, hits


