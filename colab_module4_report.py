def extract_tender_number_from_filenames() -> str:
    names: List[str] = []
    if "uploaded_files" in globals() and uploaded_files:
        names.extend(list(uploaded_files.keys()))
    # также имена источников индекса (архивы/вложенные)
    try:
        names.extend(list(set(rag_index.sources)))
    except Exception:
        pass

    patterns = [
        re.compile(r"(B\d{10,12})", re.IGNORECASE),
        re.compile(r"\b(\d{18,36})\b"),  # ИКЗ
        re.compile(r"\b(\d{10,17})\b"),
    ]
    for name in names:
        for pat in patterns:
            m = pat.search(str(name))
            if m:
                return m.group(1).upper() if m.group(1)[0].isalpha() else m.group(1)
    return ""


def extract_tender_number_from_text(raw: str) -> str:
    if not raw or raw == "Не указано":
        return ""
    patterns = [
        r"\b(B\d{10,12})\b",
        r"\b(\d{18,36})\b",
        r"\b([A-Za-z]\d{10,})\b",
        r"\b(\d{10,17})\b",
    ]
    for pat in patterns:
        m = re.search(pat, raw, flags=re.IGNORECASE)
        if m:
            num = m.group(1)
            return num.upper() if num[0].isalpha() else num
    return ""


def build_report_filename(tender_no: str) -> str:
    date_s = ANALYSIS_DATE.strftime("%Y%m%d")
    time_s = ANALYSIS_DATE.strftime("%H%M%S")
    if tender_no:
        safe = re.sub(r"[^\w\-]+", "_", tender_no).strip("_")
        return f"Анализ_тендера_{safe}_{date_s}.txt"
    return f"Анализ_тендера_{date_s}_{time_s}.txt"


